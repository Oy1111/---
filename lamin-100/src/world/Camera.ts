const sm = (x: number) => {
  const c = clamp(x);
  return c * c * (3 - 2 * c);
};

export const camAt = (t: number) => {
  let i = 0;
  while (i < KEYS.length - 2 && KEYS[i + 1][0] <= t) i++;
  const [t0, x0, y0, z0] = KEYS[i];
  const [t1, x1, y1, z1] = KEYS[i + 1];
  const u = sm((t - t0) / (t1 - t0));
  const z = Math.exp(Math.log(z0) + (Math.log(z1) - Math.log(z0)) * u);
  let w = u;
  if (Math.abs(Math.log(z1 / z0)) > 0.5) w = (1 / z0 - 1 / z) / (1 / z0 - 1 / z1);
  // let håndholdt drift (mindre når der er zoomet langt ind)
  const d = z > 4.5 ? 0 : 1 / Math.sqrt(z);
  const cx = x0 + (x1 - x0) * w + Math.sin(t * 0.9) * 6 * d + Math.sin(t * 2.3) * 2 * d;
  const cy = y0 + (y1 - y0) * w + Math.cos(t * 0.7) * 5 * d;
  return { cx, cy, z };
};
